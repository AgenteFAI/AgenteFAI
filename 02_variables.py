# ===========================================
# Lección 2: Variables - Guardar información
# ===========================================
#
# Una variable es como una caja con etiqueta.
# Guardas algo dentro y luego puedes usarlo después.

nombre = "María"
edad = 25
ciudad = "Buenos Aires"

# Ahora usamos esas variables para mostrar un mensaje:
print("Me llamo", nombre)
print("Tengo", edad, "años")
print("Vivo en", ciudad)

# -------------------------------------------
# Tipos de datos básicos:
# -------------------------------------------
# Texto (string):    "hola"     (siempre entre comillas)
# Número entero:     42         (sin comillas)
# Número decimal:    3.14       (con punto, no coma)
# Verdadero/Falso:   True/False (se llama "booleano")

precio = 9.99
en_oferta = True

print("El precio es", precio)
print("¿Está en oferta?", en_oferta)

